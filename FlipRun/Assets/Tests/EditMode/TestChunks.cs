namespace FlipRun.Tests
{
    /// <summary>テスト用のチャンクを文字列から作る。rows は上（y=+4）から順に9行。</summary>
    static class TestChunks
    {
        public static ChunkData Make(params string[] rows)
        {
            return new ChunkData { id = "test", difficulty = 1, width = rows[0].Length, height = rows.Length, rows = rows };
        }

        public static ChunkData Flat()
        {
            return Make(
                "11111111111111111111",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "11111111111111111111");
        }

        /// <summary>床に穴（8〜12列）。</summary>
        public static ChunkData FloorHole()
        {
            return Make(
                "11111111111111111111",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "11111111000001111111");
        }

        /// <summary>床にトゲ（10列目）。</summary>
        public static ChunkData FloorSpike()
        {
            return Make(
                "11111111111111111111",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000002000000000",
                "11111111111111111111");
        }

        /// <summary>床に高さ1の壁（10列目）。</summary>
        public static ChunkData FloorWall()
        {
            return Make(
                "11111111111111111111",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000001000000000",
                "11111111111111111111");
        }

        /// <summary>通路を完全にふさぐ壁。クリア不可能。</summary>
        public static ChunkData BlockedWall()
        {
            return Make(
                "11111111111111111111",
                "00000000001000000000",
                "00000000001000000000",
                "00000000001000000000",
                "00000000001000000000",
                "00000000001000000000",
                "00000000001000000000",
                "00000000001000000000",
                "11111111111111111111");
        }

        /// <summary>同じ場所で床と天井の両方に8列の穴。どちらに立っていても落ちる。クリア不可能。</summary>
        public static ChunkData DoubleHole()
        {
            return Make(
                "11111100000000111111",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "11111100000000111111");
        }

        /// <summary>床に穴、その少し先で天井に穴。一度天井へ反転し、また床へ戻る必要がある。</summary>
        public static ChunkData NeedsTwoFlips()
        {
            return Make(
                "11111111111111000011",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "00000000000000000000",
                "11111100000111111111");
        }
    }
}
